#!/usr/bin/env node
// Builds the in-browser C# compiler (compiler/, .NET 10 SDK) and copies it to public/compiler/
// (git-ignored). Run once after cloning and whenever compiler/ changes; CI runs it before `vite build`.
//
//   npm run compiler:build
//
// Only what the app downloads is copied: the .js loader files and the gzip copies of the .wasm
// files (the worker unpacks them itself – GitHub Pages may not compress .wasm).
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib/batch.mjs';

const project = join(ROOT, 'compiler', 'Quizilla.Compiler.csproj');
const out = join(ROOT, 'compiler', 'bin', 'publish');
const target = join(ROOT, 'public', 'compiler', '_framework');

rmSync(out, { recursive: true, force: true });
const r = spawnSync(process.env.DOTNET ?? 'dotnet', ['publish', project, '-c', 'Release', '-o', out, '-nologo', '-clp:ErrorsOnly'], {
  stdio: 'inherit',
  env: { ...process.env, DOTNET_CLI_TELEMETRY_OPTOUT: '1', DOTNET_NOLOGO: '1' },
});
if (r.status !== 0) { console.error('dotnet publish failed'); process.exit(r.status ?? 1); }

const src = join(out, 'wwwroot', '_framework');
rmSync(join(ROOT, 'public', 'compiler'), { recursive: true, force: true });
mkdirSync(target, { recursive: true });
let bytes = 0;
let count = 0;
for (const f of readdirSync(src)) {
  const p = join(src, f);
  if (statSync(p).isDirectory()) continue;
  if (f.endsWith('.br')) continue;                       // brotli copies: not used
  if (f.endsWith('.wasm') || f.endsWith('.js.gz')) continue; // raw wasm: we fetch the .gz; js: raw
  cpSync(p, join(target, f));
  bytes += statSync(p).size;
  count++;
}
writeFileSync(join(ROOT, 'public', 'compiler', 'README.txt'),
  'Generated by `npm run compiler:build` from compiler/ – do not edit, not in git.\r\n');
console.log(`public/compiler/_framework: ${count} files, ${(bytes / 1048576).toFixed(1)} MB`);
if (!existsSync(join(target, 'dotnet.js'))) { console.error('dotnet.js missing'); process.exit(1); }
