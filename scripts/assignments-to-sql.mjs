#!/usr/bin/env node
// Turns coding assignments (assignments/<slug>/) into the next numbered SQL update
// (supabase/updates/NNN_assignments_<name>.sql). Requires 030_coding_assignments.sql.
//
//   npm run a:sql                          → all assignments
//   npm run a:sql -- assignments/hotel …   → only these
//   --include-pending   make "pending" assignments visible too (default: only "approved")
//   --name=<text>       file name part (default "all", or the slug for one assignment)
//   --dry               print the summary only, don't write the file
//
// Every assignment must pass `npm run a:verify` first (check.status "ok" with the current hash),
// so the scenarios in the database are known to match the reference solution.
// Re-runnable: assignments are matched by slug, so running it again updates them.
// "rejected" (and "pending" without --include-pending) assignments are stored but hidden.
// Visibility to users is ALSO limited by quiz.config 'assignments_access' (see 030).
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { flag, option, ROOT, UPDATES_DIR } from './lib/batch.mjs';
import { assignmentDirs, loadAssignment, validateAssignment, checkHash, linesToText, briefText } from './lib/assignments.mjs';

const args = process.argv.slice(2);
const INCLUDE_PENDING = flag(args, 'include-pending');
const DRY = flag(args, 'dry');

const dirs = assignmentDirs(args);
if (!dirs.length) { console.error('No assignments found.'); process.exit(1); }

const list = [];
let problems = 0;
for (const dir of dirs) {
  const a = loadAssignment(dir);
  const { errors } = validateAssignment(a);
  if (errors.length) {
    console.error(`✖ ${a.data.slug ?? dir}: ${errors.length} format error(s) – run npm run a:verify`);
    problems++;
    continue;
  }
  if (a.data.check?.status !== 'ok' || a.data.check.hash !== checkHash(a)) {
    console.error(`✖ ${a.data.slug}: not verified since the last change – run npm run a:verify`);
    problems++;
    continue;
  }
  list.push(a);
}
if (problems) { console.error(`\n${problems} assignment(s) not ready – nothing written.`); process.exit(1); }

/** Dollar-quoted literal with a tag that does not occur in the text (same as questions-to-sql). */
function lit(s) {
  if (s == null) return 'null';
  const text = String(s);
  let tag = 'q';
  for (let i = 1; text.includes(`$${tag}$`); i++) tag = `q${i}`;
  return `$${tag}$${text}$${tag}$`;
}
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;
// Multi-line text goes through a JSON string, so the file's CRLF line ends never end up in the data.
const text = (s) => `(${lit(JSON.stringify(String(s)))}::jsonb #>> '{}')`;
const isActive = (d) => d.status === 'approved' || (INCLUDE_PENDING && d.status === 'pending');

function assignmentSql(a) {
  const d = a.data;
  const scenarios = d.scenarios.map((s) => ({
    name_sk: s.sk, name_en: s.en, input: linesToText(s.input), expected: linesToText(s.expected), points: s.points,
  }));
  return `-- ${d.slug} (${d.status}${isActive(d) ? '' : ', hidden'})
insert into quiz.assignments (slug, sort_order, is_active, title_sk, title_en, brief_sk, brief_en,
                              max_points, time_limit_ms, scenarios, design, reference_solution)
values (${lit(d.slug)}, ${d.sort_order}, ${isActive(d)}, ${lit(d.sk.title)}, ${lit(d.en.title)},
        ${text(briefText(d.sk.brief))},
        ${text(briefText(d.en.brief))},
        ${d.max_points}, ${d.time_limit_ms},
        ${json(scenarios)},
        ${json(d.design)},
        ${text(a.solution)})
on conflict (slug) do update set
  sort_order = excluded.sort_order, is_active = excluded.is_active,
  title_sk = excluded.title_sk, title_en = excluded.title_en,
  brief_sk = excluded.brief_sk, brief_en = excluded.brief_en,
  max_points = excluded.max_points, time_limit_ms = excluded.time_limit_ms,
  scenarios = excluded.scenarios, design = excluded.design,
  reference_solution = excluded.reference_solution, updated_at = now();
`;
}

const existing = existsSync(UPDATES_DIR) ? readdirSync(UPDATES_DIR) : [];
const nextNo = Math.max(0, ...existing.map((f) => Number(/^(\d{3})_/.exec(f)?.[1] ?? 0))) + 1;
const name = (option(args, 'name') ?? (list.length === 1 ? list[0].data.slug : 'all')).replace(/[^a-z0-9-]+/gi, '-').toLowerCase();
const file = join(UPDATES_DIR, `${String(nextNo).padStart(3, '0')}_assignments_${name}.sql`);
const today = new Date().toISOString().slice(0, 10);
const active = list.filter((a) => isActive(a.data));

const sql = `-- Quizilla – coding assignments: ${list.map((a) => a.data.slug).join(', ')} (${today})
--   Generated by scripts/assignments-to-sql.mjs from assignments/<slug>/ – do not edit by hand,
--   change the JSON / Solution.cs, run npm run a:verify and generate a new file instead.
--   Visible: ${active.length ? active.map((a) => a.data.slug).join(', ') : 'none'}${INCLUDE_PENDING ? ' (pending included)' : ''}.
--   Who may see assignments at all is set by quiz.config 'assignments_access' (030).
-- Run after 030:  npm run q:import -- supabase/updates/${relative(UPDATES_DIR, file)}   Safe to re-run.
begin;

${list.map(assignmentSql).join('\n')}
commit;

-- check: imported assignments
select slug, is_active, title_en, jsonb_array_length(scenarios) as scenarios, max_points, updated_at
  from quiz.assignments order by sort_order, slug;
`;

console.log(`${list.length} assignment(s), ${active.length} visible: ${active.map((a) => a.data.slug).join(', ') || '–'}`);
if (DRY) { console.log('(dry run – nothing written)'); process.exit(0); }
writeFileSync(file, sql.replace(/\r?\n/g, '\r\n'), 'utf8');
console.log(`wrote ${relative(ROOT, file)}`);
